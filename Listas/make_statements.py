"""Generate the statement fragments printed before each solution in the practice-list solutions PDFs.

For every `Listas/pratica-lecture-0N.md`, each `#### n. Label` block is converted with pandoc
(Markdown + TeX math -> LaTeX) into `Listas/pratica-lecture-0N-solutions/stmt/item-NN.tex`.
The list stays the single source: rerun this script after editing a list, then recompile the PDF.

Kept from each block: the source line, the verbatim statement, any "Referred to in the statement"
material and notes. Dropped: the HTML id comment and the "Moved here from" bookkeeping line.
Image paths `figures/...` become `../figures/...` (relative to the solutions folder); Obsidian
links `[[target|text]]` become `text`.

Usage (from the repo root or anywhere):  python Listas/make_statements.py [N ...]
Fails loudly if pandoc is missing or a list has no items.
"""
import re
import subprocess
import sys
from pathlib import Path

LISTAS = Path(__file__).resolve().parent
ITEM = re.compile(r"^#### (\d+)\. .*$", re.M)
STOP = re.compile(r"^#{1,4} ", re.M)


def blocks(md: str):
    """Yield (item number, block body) for each '#### n. Label' block of a list."""
    for m in ITEM.finditer(md):
        nxt = STOP.search(md, m.end())
        yield int(m.group(1)), md[m.end(): nxt.start() if nxt else len(md)]


def clean(body: str) -> str:
    """Drop bookkeeping lines and rewrite paths and wiki links before conversion."""
    body = re.sub(r"<!--.*?-->", "", body, flags=re.S)
    body = "\n".join(l for l in body.splitlines()
                     if not re.match(r"\s*\**\*?Moved here from", l))
    body = body.replace("](figures/", "](../figures/")
    body = re.sub(r"\[\[([^\]|]+)\|([^\]]+)\]\]", r"\2", body)
    body = re.sub(r"\[\[([^\]]+)\]\]", r"\1", body)
    return body.strip() + "\n"


def to_latex(md: str) -> str:
    """Convert one Markdown block to a LaTeX fragment with pandoc."""
    out = subprocess.run(
        ["pandoc", "-f", "markdown+tex_math_dollars+raw_tex-implicit_figures-auto_identifiers",
         "-t", "latex", "--wrap=preserve"],
        input=md.encode("utf-8"), capture_output=True, check=True)
    return out.stdout.decode("utf-8")


def main(lectures):
    for n in lectures:
        md = (LISTAS / f"pratica-lecture-0{n}.md").read_text(encoding="utf-8")
        outdir = LISTAS / f"pratica-lecture-0{n}-solutions" / "stmt"
        outdir.mkdir(exist_ok=True)
        count = 0
        for k, body in blocks(md):
            tex = to_latex(clean(body))
            (outdir / f"item-{k:02d}.tex").write_text(
                f"% Generated by Listas/make_statements.py from pratica-lecture-0{n}.md, item {k}. Do not edit.\n"
                + tex, encoding="utf-8")
            count += 1
        if count == 0:
            sys.exit(f"pratica-lecture-0{n}.md: no '#### n.' items found")
        print(f"Lecture {n}: {count} statements -> {outdir.relative_to(LISTAS.parent)}")


if __name__ == "__main__":
    main([int(a) for a in sys.argv[1:]] or range(1, 9))
