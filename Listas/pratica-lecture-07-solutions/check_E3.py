# ---- item 19 (mwg-13-b-1): three examples = Figures 13.B.1, 13.B.2, 13.B.3
x = sp.symbols("x", positive=True)


def curves_uniform(lo, hi, rho):
    E = (lo + x) / 2  # E[theta | theta <= x], uniform on [lo, hi]
    return E, rho * x


# Fig. 13.B.1: uniform on [1,2], r(theta) = 0.9 theta <= theta: interior crossing, all should work
E1, r1 = curves_uniform(1, 2, R_(9, 10))
assert sp.solve(sp.Eq(E1, r1), x) == [R_(5, 4)]
assert E1.subs(x, R_(5, 4)) == R_(9, 8) == r1.subs(x, R_(5, 4))  # wage w* = 9/8
assert r1.subs(x, 2) > R_(3, 2)  # r(theta_bar) > E[theta]: nobody-all corner is not an equilibrium
assert r1.subs(x, 1) < E1.subs(x, 1)  # r(theta_low) < theta_low = E at the lowest type
assert sp.simplify(x - r1) == x / 10  # r(theta) < theta everywhere: efficient set is the whole interval
# Fig. 13.B.2: uniform on [0,2], r(theta) = alpha theta, alpha > 1/2: E(x) = x/2 < alpha x for all x > 0
for alpha in (R_(3, 5), R_(4, 5), R_(9, 10)):
    assert sp.solve(sp.Eq(x / 2, alpha * x), x) == []  # only x = 0 (excluded by positivity)
assert sp.solve(sp.Eq(x / 2, R_(2, 5) * x), x) == [] and R_(2, 5) < R_(1, 2)  # alpha < 1/2: E(x) > r(x)
# Fig. 13.B.3: piecewise-constant density on [0,1], r(theta) = 0.6 theta, three interior equilibria
edges = [R_(0), R_(1, 5), R_(3, 5), R_(4, 5), R_(1)]
wts = [R_(1, 20), R_(5, 20), R_(1, 20), R_(13, 20)]
dens = [w / (edges[k + 1] - edges[k]) for k, w in enumerate(wts)]
assert sum(wts) == 1
rho = R_(3, 5)


def Ecurve(xv):
    """E[theta | theta <= xv] for the piecewise-constant density (sympy expression in xv)."""
    mass = tot = 0
    for k in range(4):
        hi = sp.Min(edges[k + 1], xv)
        mass += dens[k] * sp.Max(hi - edges[k], 0)
        tot += dens[k] * sp.Max(hi ** 2 - edges[k] ** 2, 0) / 2
    return tot / mass


roots = []
for k in range(4):  # solve E(x) = rho x on each density piece
    mass = sum(dens[j] * (edges[j + 1] - edges[j]) for j in range(k)) + dens[k] * (x - edges[k])
    tot = sum(dens[j] * (edges[j + 1] ** 2 - edges[j] ** 2) / 2 for j in range(k)) + dens[k] * (x ** 2 - edges[k] ** 2) / 2
    for s in sp.solve(sp.Eq(tot, rho * x * mass), x):
        if s.is_real and edges[k] < s <= edges[k + 1]:
            roots.append(s)
roots = sorted(roots)
assert len(roots) == 3 and all(abs(float(Ecurve(r)) - 0.6 * float(r)) < 1e-12 for r in roots), roots
w_star = [float(rho * r) for r in roots]
assert w_star == sorted(w_star)  # higher cutoff = higher wage = Pareto ranking of the three equilibria
xs_g = np.linspace(0.002, 1, 4001)
Eg = np.array([float(Ecurve(sp.Float(v))) for v in xs_g[::40]])
assert (np.diff(Eg) > 0).all()  # E is increasing (f > 0)
print("mwg-13-b-1: Fig. B.1 root 5/4 (w = 9/8); Fig. B.2 only the corner x = 0; Fig. B.3 roots",
      [round(float(r), 4) for r in roots], "wages", [round(v, 4) for v in w_star])


def fmt(pts):
    return " ".join(f"({a:.3f},{b:.3f})" for a, b in pts)


def panel(lo, hi, ymax, rfun, Efun, ymin=0.0, W=4.1, H=3.3):
    xs = np.linspace(lo + 1e-3, hi, 60)
    sx, sy = W / (hi - lo), H / (ymax - ymin)
    P = lambda a, b: ((a - lo) * sx, (b - ymin) * sy)
    out = [r"\begin{tikzpicture}[font=\scriptsize]",
           rf"\draw[->] (0,0) -- ({W + 0.2:.2f},0) node[right]{{$\hat\theta$}};",
           rf"\draw[->] (0,0) -- (0,{H + 0.2:.2f});",
           rf"\draw[gray,dashed] {fmt([P(a, a) for a in (max(lo, ymin), min(hi, ymax))]).replace(') (', ') -- (')};",
           rf"\draw[thick,hdr] plot[smooth] coordinates {{{fmt([P(a, rfun(a)) for a in xs])}}};",
           rf"\draw[thick,ans] plot[smooth] coordinates {{{fmt([P(a, Efun(a)) for a in xs])}}};",
           rf"\node[below] at ({(hi - lo) * sx:.2f},0) {{$\bar\theta$}};",
           r"\end{tikzpicture}"]
    return "\n".join(out)


f1 = panel(1, 2, 2.0, lambda a: 0.9 * a, lambda a: (1 + a) / 2, ymin=0.8)
f2 = panel(0, 2, 2.0, lambda a: 0.8 * a, lambda a: a / 2)
Efl = lambda a: float(Ecurve(sp.Float(a)))
f3 = panel(0, 1, 1.0, lambda a: 0.6 * a, Efl)
(HERE / "fig-mwg13b.tex").write_text(
    "% Generated by check_E3.py. Three diagrams for item 19 (blue: r, green: E[theta|r<=w], dashed: 45 degrees).\n"
    r"\begin{center}" + "\n" + f1 + "\\quad\n" + f2 + "\\quad\n" + f3 + "\n\\end{center}\n", encoding="utf-8")

# ---- item 20 (mwg-13-b-2): every competitive equilibrium is inefficient
# worked example: uniform on [1,2], r(theta) = 2 theta - 3/2 (crosses theta at 3/2)
r20 = 2 * x - R_(3, 2)
assert sp.solve(sp.Eq(r20, x), x) == [R_(3, 2)] and sp.simplify(r20 - x).subs(x, R_(5, 4)) < 0
eq = sp.solve(sp.Eq(r20, (1 + x) / 2), x)
assert eq == [R_(4, 3)] and R_(4, 3) < R_(3, 2)
assert r20.subs(x, 2) > 2 > R_(3, 2)  # r(theta_bar) > E[theta]: the all-work corner fails
assert R_(1, 1) - r20.subs(x, 1) > 0  # low corner: r(1) = 1/2 < 1 = theta_low
loss = sp.integrate(x - r20, (x, R_(4, 3), R_(3, 2)))
assert loss == R_(1, 72)  # aggregate surplus lost (density 1 on [1,2])
# random check: any increasing r crossing theta once from below, any positive density -> all CE cutoffs < theta_o
random.seed(3)
for _ in range(200):
    n = 6
    br = np.linspace(0.0, 1.0, n + 1)
    w = np.array([random.uniform(0.2, 1.0) for _ in range(n)])
    w /= w.sum()
    dd = w / np.diff(br)
    th0 = random.uniform(0.2, 0.8)
    slope = random.uniform(1.2, 3.0)
    rr = lambda t: th0 + slope * (t - th0)  # r(th0) = th0, r > theta above, < below; increasing

    def E_(t):
        tot = m = 0.0
        for k in range(n):
            hi = min(br[k + 1], t)
            if hi > br[k]:
                m += dd[k] * (hi - br[k])
                tot += dd[k] * (hi ** 2 - br[k] ** 2) / 2
        return tot / m

    grid = np.linspace(1e-4, 1, 3000)
    gvals = np.array([rr(t) - E_(t) for t in grid])
    cuts = [grid[i] for i in range(len(grid) - 1) if gvals[i] * gvals[i + 1] < 0]
    assert all(c < th0 - 1e-6 for c in cuts)  # any interior equilibrium has cutoff below theta_o
    assert rr(1.0) > E_(1.0) or rr(1.0) > 1.0  # all-work corner fails (r(theta_bar) > theta_bar > E[theta])
print("mwg-13-b-2: example cutoff 4/3 < 3/2, surplus loss 1/72; 200 random (f, r) draws: every CE cutoff < theta_o")

# ---- item 21 (tadelis-12-7): trading places
th, k = sp.symbols("theta k", positive=True)  # k = value of i's house to j divided by v_i
v = sp.symbols("v", positive=True)
Ev = sp.integrate(v, (v, 0, th)) / th  # E[v_j | v_j <= theta_j]
assert sp.simplify(Ev - th / 2) == 0
t1, t2 = sp.symbols("t1 t2", positive=True)


def fixed_points(kk):
    thr = lambda tj: sp.Min(1, kk * tj / 2)  # accept iff v_i <= k E[v_j | j accepts] = k tj / 2
    cand = {(0, 0)}
    for a in (R_(0), R_(1, 4), R_(1, 2), R_(3, 4), R_(1)):  # grid scan for fixed points of the best-reply map
        for b in (R_(0), R_(1, 4), R_(1, 2), R_(3, 4), R_(1)):
            if thr(b) == a and thr(a) == b:
                cand.add((a, b))
    return cand


assert fixed_points(R_(3, 2)) == {(0, 0)}  # (a): theta = 3/4 theta -> 0
assert fixed_points(R_(5, 2)) == {(0, 0), (1, 1)}  # (b): 5/4 theta capped at 1
for kk, expect in ((R_(3, 2), 3 / 4), (R_(5, 2), 5 / 4)):
    assert sp.simplify(kk / 2 - expect) == 0
# interior fixed points of theta_i = (k/2) theta_j with both < 1: (k/2)^2 theta = theta, so only theta = 0 unless k = 2
assert all((kk / 2) ** 2 != 1 for kk in (R_(3, 2), R_(5, 2)))
# gain from accepting is P(j accepts) * (k E[v_j|acc] - v_i), decreasing in v_i -> threshold structure
gain = lambda vi, tj, kk: (tj) * (kk * tj / 2 - vi)
assert all(gain(F(a, 10), F(1, 2), F(3, 2)) >= gain(F(b, 10), F(1, 2), F(3, 2)) for a in range(0, 10) for b in range(a, 11))
print("tadelis-12-7: (a) theta = 3/4 theta -> theta_i = 0 only; (b) theta_i = min(1, 5/4 theta_j): thresholds (0,0) and (1,1)")

# ---- item 22 (gibbons-3-8): double auction vs Game I vs Game II
vb, vs, w = sp.symbols("v_b v_s w", positive=True)
# linear equilibrium p_b = a_b + c vb, p_s = a_s + c vs
ab, as_, c = sp.symbols("a_b a_s c")
sol = sp.solve([sp.Eq(c, R_(2, 3)), sp.Eq(ab, as_ / 3), sp.Eq(as_, (ab + c) / 3)], [ab, as_, c], dict=True)[0]
assert sol[ab] == R_(1, 12) and sol[as_] == R_(1, 4) and sol[c] == R_(2, 3)
pb, ps = R_(2, 3) * vb + R_(1, 12), R_(2, 3) * vs + R_(1, 4)
assert sp.simplify(pb - ps - R_(2, 3) * (vb - vs - R_(1, 4))) == 0  # trade iff v_b >= v_s + 1/4
price = (pb + ps) / 2
trade = lambda f: sp.integrate(sp.integrate(f, (vs, 0, vb - R_(1, 4))), (vb, R_(1, 4), 1))
P_trade = trade(1)
assert P_trade == R_(9, 32)
gain_total = trade(vb - vs)
assert gain_total == R_(9, 64)
firm_da = trade(vb - price)
worker_da = R_(1, 2) + trade(price - vs)
assert firm_da + worker_da == R_(1, 2) + R_(9, 64) == R_(41, 64)
# best-reply check for the linear equilibrium by FOC (buyer): maximise [vb - (pb + E[ps|ps<=pb])/2] P(ps<=pb)
pbv = sp.symbols("pbv")
Pw = (pbv - R_(1, 4)) / R_(2, 3)
Eps = (R_(1, 4) + pbv) / 2
U = (vb - (pbv + Eps) / 2) * Pw
assert sp.solve(sp.diff(U, pbv), pbv) == [R_(2, 3) * vb + R_(1, 12)]
# Game I: fixed wage w
trade_I = lambda f: sp.integrate(sp.integrate(f, (vs, 0, w)), (vb, w, 1))  # firm accepts iff m >= w, worker iff v <= w
S_I = sp.simplify(trade_I(vb - vs))
assert sp.simplify(S_I - w * (1 - w) / 2) == 0
assert sp.solve(sp.diff(w * (1 - w) / 2, w), w) == [R_(1, 2)] and S_I.subs(w, R_(1, 2)) == R_(1, 8)
firm_I = sp.simplify(trade_I(vb - w))
worker_I = R_(1, 2) + sp.simplify(trade_I(w - vs))
assert sp.simplify(firm_I - w * (1 - w) ** 2 / 2) == 0 and sp.simplify(worker_I - R_(1, 2) - (1 - w) * w ** 2 / 2) == 0
assert firm_I.subs(w, R_(1, 2)) == R_(1, 16) and worker_I.subs(w, R_(1, 2)) == R_(1, 2) + R_(1, 16)
# Game II: firm offers w = m/2 (maximises (m - w) w), worker accepts iff v <= w
assert sp.solve(sp.diff((vb - w) * w, w), w) == [vb / 2]
S_II = sp.integrate(sp.integrate(vb - vs, (vs, 0, vb / 2)), (vb, 0, 1))
assert S_II == R_(1, 8)
firm_II = sp.integrate(vb ** 2 / 4, (vb, 0, 1))
worker_II = R_(1, 2) + sp.integrate(sp.integrate(vb / 2 - vs, (vs, 0, vb / 2)), (vb, 0, 1))
assert firm_II == R_(1, 12) and worker_II == R_(1, 2) + R_(1, 24)
assert firm_II + worker_II - R_(1, 2) == S_II == R_(1, 8) < gain_total == R_(9, 64)
print("gibbons-3-8: DA payoffs firm", firm_da, "worker", worker_da, "(total 41/64, gains 9/64); "
      "Game I w=1/2 gains 1/8; Game II gains 1/8")

# ---- item 23 (tadelis-13-5): first price, values {4, 8}
b = sp.symbols("b", positive=True)
G = (b - 4) / (8 - b)  # cdf of the high type's bid on [4, 6]
assert G.subs(b, 4) == 0 and G.subs(b, 6) == 1
win = R_(1, 2) + R_(1, 2) * G  # prob. of winning with bid b > 4: beat every low bid, beat high bids below b
assert sp.simplify((8 - b) * win - 2) == 0  # constant payoff 2 on (4, 6]
U_unif = (8 - b) * (R_(1, 2) + R_(1, 2) * (b - 4) / 2)  # same with uniform on [4,6]
assert U_unif.subs(b, 5) == R_(9, 4) > U_unif.subs(b, 6) == 2 == sp.limit(U_unif, b, 4, "+")  # uniform fails
assert (8 - 6) * 1 == 2 and all((8 - bb) < 2 for bb in (R_(61, 10), 7, 8))  # (b): bids above 6 are dominated by 6
# low type: payoff at 4 is 0; any b > 4 wins sometimes at price b > 4 -> negative
assert all((4 - bb) * win.subs(b, bb) < 0 for bb in (R_(41, 10), 5, 6))
g = sp.diff(G, b)
assert sp.simplify(g - 4 / (8 - b) ** 2) == 0
Eb = sp.integrate(b * g, (b, 4, 6))
Emax = sp.integrate(b * sp.diff(G ** 2, b), (b, 4, 6))
rev = R_(1, 4) * 4 + R_(1, 2) * Eb + R_(1, 4) * Emax
english = R_(1, 4) * 8 + R_(3, 4) * 4
assert sp.simplify(rev) == english == 5, (sp.simplify(rev), english)
rev_unif = R_(1, 4) * 4 + R_(1, 2) * 5 + R_(1, 4) * R_(16, 3)
assert rev_unif == R_(29, 6) < 5
print("tadelis-13-5: high-type cdf (b-4)/(8-b) on [4,6] gives constant payoff 2; revenue", sp.simplify(rev),
      "= English 5; the uniform on [4,6] is NOT an equilibrium (payoff 9/4 at b=5, revenue 29/6)")

# ---- item 24 (tadelis-13-10): common values, linear bidding
th, xx, b_ = sp.symbols("theta x b", positive=True)
a_ = sp.Symbol("a", real=True)
tt = sp.symbols("t")  # tt = (x - a)/b = threshold type of the rival that the bid beats
EUt = tt * (th + tt / 2 - a_ - b_ * tt)
tstar = sp.solve(sp.diff(EUt, tt), tt)[0]
assert sp.simplify(tstar - (th - a_) / (2 * b_ - 1)) == 0
cond = sp.solve([sp.Eq(2 * b_ - 1, 1), sp.Eq(a_, 0)], [a_, b_], dict=True)
assert cond == [{a_: 0, b_: 1}]  # t* = theta for all theta
assert sp.simplify(sp.diff(EUt, tt, 2).subs(b_, 1)) == -1  # strictly concave in t
assert sp.simplify(EUt.subs({a_: 0, b_: 1, tt: th}) - th ** 2 / 2) == 0
for thv in (0.1, 0.4, 0.8):  # numerical best reply against s(theta) = theta
    f = lambda xb: -(min(max(xb, 0.0), 1.0) * (thv + min(max(xb, 0.0), 1.0) / 2 - xb))
    r = minimize_scalar(f, bounds=(0, 1), method="bounded", options={"xatol": 1e-10})
    assert abs(r.x - thv) < 1e-5 and abs(-r.fun - thv ** 2 / 2) < 1e-8
assert sp.solve(sp.Eq(th, R_(1, 2) + th / 2), th) == [1]  # private-value bid exceeds common-value bid for theta < 1
assert all(tv < R_(1, 2) + tv / 2 for tv in (R_(1, 10), R_(1, 2), R_(99, 100)))
print("tadelis-13-10: s(theta) = theta (a = 0, b = 1); payoff theta^2/2; below 1/2 + theta/2 for theta < 1 (equal at 1)")
print("all E3 checks passed")
